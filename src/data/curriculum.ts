export const introCount = baseTopics.length;

export const topics: Topic[] = [
  ...baseTopics.map((topic) => ({
    ...topic,
    words: [...topic.words, ...(extraWords[topic.id] ?? [])],
  })),
  ...extraTopics,
];

export const words: WordRef[] = topics.flatMap((topic) =>
  topic.words.map((word) => ({
    ...word,
    topicId: topic.id,
    topicTitle: topic.title,
  })),
);

export function findTopic(id: string) {
  return topics.find((topic) => topic.id === id);
}

export function topicNumber(id: string) {
  return topics.findIndex((topic) => topic.id === id) + 1;
}

export function wordOfDay(list: WordRef[], now = new Date()) {
  const start = new Date(2026, 0, 1).getTime();
  const today = new Date(now.getFullYear(), now.getMonth(), now.getDate()).getTime();
  const day = Math.round((today - start) / 86_400_000);
  const index = ((day % list.length) + list.length) % list.length;
  return list[index];
}
