import type { Topic, Word } from "../types";

type Row = [string, string, string, string, string, string, string, string?];

function pack(prefix: string, rows: Row[]): Word[] {
  return rows.map(([slug, hanzi, pinyin, vi, example, examplePinyin, exampleVi, note]) => ({
    id: `${prefix}-${slug}`,
    hanzi,
    pinyin,
    vi,
    example,
    examplePinyin,
    exampleVi,
    ...(note ? { note } : {}),
  }));
}

function topic(id: string, title: string, hanzi: string, blurb: string, tip: string, rows: Row[]): Topic {
  return { id, title, hanzi, blurb, tip, words: pack(id, rows) };
}

